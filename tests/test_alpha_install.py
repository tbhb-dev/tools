@dataclass
class World:
    """A temp HOME, a bin of fakes on PATH, and a tbhb-dev repository."""

    home: Path
    bin: Path
    repo: Path

    def prek_calls(self) -> list[list[str]]:
        log = self.bin / "prek.log"
        if not log.exists():
            return []
        return [json.loads(line) for line in log.read_text().splitlines()]

    def prek_cwds(self) -> set[str]:
        return set((self.bin / "prek.cwd").read_text().splitlines())

    def stages(self, *names: str) -> None:
        (self.bin / "prek.stages").write_text(" ".join(names))

    @property
    def hooks(self) -> Path:
        return self.repo / ".git" / "hooks"


def git(cwd: Path, *args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=cwd, capture_output=True, text=True, check=True
    ).stdout.strip()


def make_repo(path: Path, origin: str | None = ORIGIN) -> Path:
    path.mkdir(parents=True)
    git(path, "init", "-q")
    if origin:
        git(path, "remote", "add", "origin", origin)
    return path.resolve()


