def shim_env(world: World, tool: str | None) -> dict[str, str]:
    """An environment whose PATH has a fake `tbhbdev` that exits `tool`, if any."""
    shim_bin = world.bin.parent / "shim_bin"
    fake = shim_bin / "tbhbdev"
    if tool is None:
        fake.unlink(missing_ok=True)
    else:
        fake.write_text(f'#!/bin/sh\necho "tbhbdev $*"\nexit {tool}\n')
        fake.chmod(0o755)
    return {
        **os.environ,
        "PATH": f"{shim_bin}{os.pathsep}{world.bin.parent / 'git_dir'}",
    }


