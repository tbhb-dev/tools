def test_merge_events_is_idempotent_and_keeps_everything_else() -> None:
    config: Json = {
        "model": "x",
        "hooks": {
            "Stop": [{"hooks": [THEIRS]}],
            "Pre": [{"matcher": "Edit", "hooks": [THEIRS]}],
        },
        "permissions": {"allow": []},
    }
    once = install.merge_events(config, DESIRED)
    assert once == {
        "model": "x",
        "hooks": {
            "Stop": [{"hooks": [THEIRS]}],
            "Pre": [{"matcher": "Edit", "hooks": [THEIRS]}, *DESIRED["Pre"]],
            "Start": DESIRED["Start"],
        },
        "permissions": {"allow": []},
    }
    assert list(cast("Json", once["hooks"])) == ["Stop", "Pre", "Start"]
    assert install.merge_events(once, DESIRED) == once


