def install_hook(repo: Path, monkeypatch: pytest.MonkeyPatch) -> dict[str, str]:
    hooks = repo / ".git/hooks"
    (hooks / "pre-push").write_text("#!/bin/sh\n# File generated by prek\nexit 0\n")
    (hooks / "pre-push").chmod(0o755)
    install.install_pre_push_hook(hooks)
    binary = repo / "bin"
    binary.mkdir()
    tool = binary / "tbhbdev"
    tool.write_text(
        f"#!{sys.executable}\n"
        "import sys\nfrom tbhbdev.cli import main\nsys.exit(main())\n"
    )
    tool.chmod(0o755)
    monkeypatch.setenv("PATH", f"{binary}:{os.environ['PATH']}")
    monkeypatch.setenv("PYTHONPATH", pythonpath(Path(pg.__file__).parents[2]))
    env = dict(os.environ)
    env.pop("MUTANT_UNDER_TEST", None)
    return env


def push(
    repo: Path, env: dict[str, str], *args: str
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "push", *args],
        cwd=repo,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )


def test_real_pushes_through_the_installed_hook(
    repo: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    env = install_hook(repo, monkeypatch)
    remote = repo.parent / "remote.git"
    base = git(repo, "rev-parse", "HEAD")
    git(repo, "switch", "-qc", "topic")
    first = commit(repo, "first")
    assert push(repo, env, "origin", "topic").returncode == 0
    git(repo, "reset", "-q", "--hard", base)
    second = commit(repo, "second")
    # A plain push is still a rewrite: git itself refuses it before the hook.
    assert push(repo, env, "origin", "topic").returncode != 0
    # A lease push of a fetched tip passes the hook, which logs the rewrite.
    done = push(repo, env, "--force-with-lease", "origin", "topic")
    assert done.returncode == 0, done.stderr
    assert f"refs/heads/topic rewritten {first} -> {second}" in done.stderr
    assert git(remote, "rev-parse", "refs/heads/topic") == second
    # Someone else moves the branch: both the lease and the hook refuse a stale tip.
    other = repo.parent / "other"
    subprocess.run(["git", "clone", "-q", str(remote), str(other)], check=True, env=env)
    git(other, "switch", "-q", "topic")
    git(other, "config", "commit.gpgsign", "false")
    moved = commit(other, "moved")
    git(other, "push", "-q", "origin", "topic")
    git(repo, "reset", "-q", "--hard", base)
    commit(repo, "third")
    lease = push(repo, env, "--force-with-lease", "origin", "topic")
    assert lease.returncode != 0
    plain = push(repo, env, "--force", "origin", "topic")
    assert plain.returncode != 0
    assert "the remote tip is not the fetched one" in plain.stderr
    assert git(remote, "rev-parse", "refs/heads/topic") == moved
    # Main is refused by the hook even for a lease push of its fetched tip.
    git(repo, "fetch", "-q", "origin")
    git(repo, "switch", "-q", "main")
    git(repo, "reset", "-q", "--hard", base)
    commit(repo, "rewrite main")
    git(repo, "reset", "-q", "--hard", base)
    git(repo, "commit", "-q", "--allow-empty", "-m", "different")
    denied = push(repo, env, "--force-with-lease", "origin", "main")
    assert denied.returncode != 0
    assert "push to a protected branch refused" in denied.stderr


