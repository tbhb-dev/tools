def commit(repo: Path, message: str = "next", **files: str) -> str:
    for name, content in files.items():
        path = repo / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    git(repo, "add", ".")
    git(repo, "commit", "--allow-empty", "-qm", message)
    return git(repo, "rev-parse", "HEAD")


def origin_url() -> str:
    return git(Path.cwd(), "config", "remote.origin.url")


def guard(monkeypatch: pytest.MonkeyPatch, local: str, remote: str = ZERO) -> int:
    monkeypatch.setattr(
        sys,
        "stdin",
        io.StringIO(f"refs/heads/topic {local} refs/heads/topic {remote}\n"),
    )
    return alpha.main(["pre-push-guard", "origin", origin_url()], "tbhbdev alpha")


@pytest.mark.parametrize("kind", ["diverged", "forward", "new", "delete", "missing"])
def test_ancestry(
    repo: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
    kind: str,
) -> None:
    base = git(repo, "rev-parse", "HEAD")
    head = commit(repo)
    local, remote = {
        "diverged": (base, head),
        "forward": (head, base),
        "new": (head, ZERO),
        "delete": (ZERO, base),
        "missing": (head, "f" * 40),
    }[kind]
    denied = kind in {"diverged", "missing"}
    assert guard(monkeypatch, local, remote) == int(denied)
    out, err = capsys.readouterr()
    assert out == ""
    if denied:
        assert err == (
            "refs/heads/topic: non-fast-forward push refused; the remote tip is "
            "not the fetched one, so fetch and push with --force-with-lease\n"
        )
    else:
        assert err == ""


